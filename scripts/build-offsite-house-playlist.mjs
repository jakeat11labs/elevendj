// Emits src/lib/offsite-house-playlist.ts from the verified sidecar metadata
// next to each rendered MP3.
//
// Karaoke timing is produced by importing the real normalizeLyrics() rather
// than reimplementing it, so the curated house tracks and live generations can
// never drift apart in how their lyrics are timed. That module is marked
// `server-only`, which throws outside a server bundle, so the import is stubbed
// for the length of this script.
//
// Run: node --experimental-strip-types scripts/build-offsite-house-playlist.mjs

import { execFile } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { registerHooks } from "node:module";
import path from "node:path";
import { promisify } from "node:util";

const run = promisify(execFile);

registerHooks({
  resolve(specifier, context, nextResolve) {
    if (specifier === "server-only") {
      return { url: "data:text/javascript,", shortCircuit: true };
    }
    return nextResolve(specifier, context);
  },
});

const { normalizeLyrics, parseWordTimestamps } = await import(
  "../src/lib/generation/lyrics.ts"
);

/** Rendered sets, in the order they should appear in the manifest. */
const SETS = [
  { dir: "public/offsite/cancun-2026/house-playlist", set: "eleven" },
  { dir: "public/offsite/cancun-2026/island-set", set: "island" },
];

/** Takes that were reviewed and cut. Kept here so the reason survives. */
const RETIRED = new Set([
  "C02", // Room Block Riddim — replaced by C11 on the same reggae recipe.
]);

async function durationMs(file) {
  const { stdout } = await run("ffprobe", [
    "-v", "error",
    "-show_entries", "format=duration",
    "-of", "default=noprint_wrappers=1:nokey=1",
    file,
  ]);
  return Math.round(Number(stdout.trim()) * 1000);
}

const tracks = [];

for (const { dir, set } of SETS) {
  const names = (await readdir(dir)).filter((n) => n.endsWith(".json")).sort();
  for (const name of names) {
    const meta = JSON.parse(await readFile(path.join(dir, name), "utf8"));
    if (RETIRED.has(meta.id)) {
      console.log(`${meta.id} ${meta.title} — retired, skipped`);
      continue;
    }

    const words = parseWordTimestamps(meta);
    const lyrics = normalizeLyrics(meta, words);
    const ms = await durationMs(path.join(dir, meta.file));

    tracks.push({
      id: meta.id,
      set,
      // The curated title, not the model's own (meta.generatedTitle). The model
      // often shortens it and loses the joke — "In The Ocean" for what the set
      // list calls "Out Of Office, In The Ocean".
      title: meta.title,
      // The one-line joke, shown under the title on the stage screen. Far
      // friendlier than surfacing the raw generation prompt.
      blurb: meta.concept,
      genre: meta.genre,
      url: `/${path.relative("public", path.join(dir, meta.file))}`,
      durationMs: ms,
      lyrics,
    });

    console.log(
      `${meta.id} ${meta.title} — ${(ms / 1000).toFixed(0)}s, ` +
        `${lyrics ? `${lyrics.sections.length} sections` : "NO LYRICS"}`
    );
  }
}

const withoutLyrics = tracks.filter((t) => !t.lyrics);
if (withoutLyrics.length > 0) {
  console.warn(
    `\nWARNING: no karaoke for ${withoutLyrics.map((t) => t.id).join(", ")}`
  );
}

// One track per line: keeps the file ~200 KB instead of ~600 KB of indentation
// while still giving a one-line-per-track diff when a take is recut.
const entries = tracks.map((t) => `  ${JSON.stringify(t)},`).join("\n");

const body = `// Curated Offsite house playlist — the approved Cancún 2026 tracks.
//
// Pre-rendered, reviewed assets rather than per-session generations: every room
// draws from this one shared list, so the Offsite sounds the same everywhere and
// idle rooms cost no generation credits. AutoDJ still generates live music once
// this list is exhausted (see src/lib/autodj-pool.ts).
//
// Generated by scripts/build-offsite-house-playlist.mjs from the verified
// metadata beside each MP3 — do not hand-edit the entries. Lyrics were timed by
// the same normalizeLyrics() the live pipeline uses, so karaoke behaves
// identically for house tracks and audience requests.
//
// Server-only on purpose: the embedded karaoke timings are a few hundred KB and
// must never be pulled into a client bundle. Rooms receive these tracks through
// the normal queue API, exactly like an audience request.

import "server-only";

import type { Lyrics } from "@/lib/status";

export type OffsiteHouseTrack = {
  id: string;
  /** "eleven" = ElevenLabs product block, "island" = Cancún block. */
  set: "eleven" | "island";
  title: string;
  /** One-line premise, shown under the title on the stage screen. */
  blurb: string;
  genre: string;
  url: string;
  durationMs: number;
  lyrics: Lyrics | null;
};

export const OFFSITE_HOUSE_PLAYLIST: readonly OffsiteHouseTrack[] = [
${entries}
];

/**
 * Shuffle-bag rotation, matching the station-ID behaviour: every track plays
 * once before any repeats, and a reshuffle can't put the same track back to
 * back. \`random\` is injectable so the ordering is testable.
 */
export function createHouseRotation(
  tracks: readonly OffsiteHouseTrack[] = OFFSITE_HOUSE_PLAYLIST,
  random: () => number = Math.random
): () => OffsiteHouseTrack | null {
  let bag: OffsiteHouseTrack[] = [];
  let lastId: string | null = null;

  return () => {
    if (tracks.length === 0) return null;
    if (bag.length === 0) {
      bag = [...tracks];
      for (let i = bag.length - 1; i > 0; i -= 1) {
        const j = Math.floor(random() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
      // Draws come off the end of the bag, so the repeat guard has to look at
      // the last entry rather than the first.
      const next = bag.length - 1;
      if (bag.length > 1 && bag[next].id === lastId) {
        [bag[next], bag[0]] = [bag[0], bag[next]];
      }
    }
    const next = bag.pop() ?? null;
    if (next) lastId = next.id;
    return next;
  };
}
`;

const out = "src/lib/offsite-house-playlist.ts";
await writeFile(out, body);
console.log(
  `\n${tracks.length} tracks → ${out} (${(body.length / 1024).toFixed(0)} KB)`
);
